        private void cargarUltimasCuentas() {
        try {
            java.sql.Connection con = Conexion.conectar();
            java.sql.Statement st = con.createStatement();

            String sql = "SELECT id_usuario, nombre, usuario FROM Usuario " +
                         "WHERE tipo = 'CLIENTE' ORDER BY id_usuario DESC LIMIT 4";

            java.sql.ResultSet rs = st.executeQuery(sql);

            javax.swing.DefaultListModel<String> modelo = new javax.swing.DefaultListModel<>();
            idsEnLista.clear();
            correosEnLista.clear();

            while (rs.next()) {
                int id = rs.getInt("id_usuario");
                String nombre = rs.getString("nombre");
                String correo = rs.getString("usuario");

                modelo.addElement(nombre + " (" + correo + ")");
                idsEnLista.add(id);
                correosEnLista.add(correo);
            }

            listaCuentas.setModel(modelo);
            con.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar cuentas: " + e.getMessage());
        }
    }

