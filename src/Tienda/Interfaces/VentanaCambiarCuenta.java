    private void btnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarActionPerformed
        // TODO add your handling code here:
        int indice = listaCuentas.getSelectedIndex();

        if (indice == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una cuenta de la lista");
            return;
        }

        int idElegido = idsEnLista.get(indice);
        String correoElegido = correosEnLista.get(indice);

        javax.swing.JPasswordField campoContrasena = new javax.swing.JPasswordField();
        int opcion = javax.swing.JOptionPane.showConfirmDialog(
            this, campoContrasena, "Ingresa la contraseña de " + correoElegido,
            javax.swing.JOptionPane.OK_CANCEL_OPTION
        );

        if (opcion != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        String contrasenaIngresada = new String(campoContrasena.getPassword());

        try {
            java.sql.Connection con = Conexion.conectar();

            String sql = "SELECT * FROM Usuario WHERE id_usuario = ? AND contrasena = ?";
            java.sql.PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, idElegido);
            st.setString(2, contrasenaIngresada);

            java.sql.ResultSet rs = st.executeQuery();

            if (rs.next()) {

    SesionActual.idUsuario = rs.getInt("id_usuario");
    SesionActual.nombre = rs.getString("nombre");
    SesionActual.correo = rs.getString("usuario");
    SesionActual.telefono = rs.getString("telefono");

    // Buscar el cliente correspondiente al nuevo usuario
    String sqlCliente =
            "SELECT id_cliente FROM Cliente WHERE id_usuario = ?";

    java.sql.PreparedStatement stCliente =
            con.prepareStatement(sqlCliente);

    stCliente.setInt(1, SesionActual.idUsuario);

    java.sql.ResultSet rsCliente =
            stCliente.executeQuery();

    if (rsCliente.next()) {

        SesionActual.idCliente =
                rsCliente.getInt("id_cliente");

    } else {

        SesionActual.idCliente = 0;

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "La cuenta no tiene un cliente asociado."
        );

        rsCliente.close();
        stCliente.close();
        con.close();
        return;
    }

    rsCliente.close();
    stCliente.close();

    con.close();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Cuenta cambiada correctamente"
            
    );

    VentanaInicioCliente inicio = new VentanaInicioCliente();
    inicio.setVisible(true);
    this.dispose();

            } else {
                con.close();
                javax.swing.JOptionPane.showMessageDialog(this, "Contraseña incorrecta");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSeleccionarActionPerformed

